# -*- coding: utf-8 -*-
"""构建分层难例评测集-30题（10改写+10跨文档组合+10库外）并导入 EvalAgent。"""
import json, os, urllib.request

KB_ID = 6
token = os.environ['EVAL_TOKEN']
opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

def api(method, path, payload=None):
    req = urllib.request.Request('http://localhost:8000/api/v1' + path,
        data=json.dumps(payload).encode() if payload is not None else None,
        headers={'Authorization': 'Bearer ' + token, 'Content-Type': 'application/json'}, method=method)
    try:
        return json.load(opener.open(req, timeout=60))
    except urllib.error.HTTPError as e:
        return {'err': e.code, 'body': e.read().decode()[:300]}

